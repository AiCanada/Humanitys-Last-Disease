def _chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)


def png_icon(size: int) -> bytes:
    """A square PNG: the panel's green with a white H.

    The square is full bleed with no transparency. iOS and Android round the
    corners themselves, and a transparent corner shows up black on an iPhone.
    The H stays inside the middle 60 percent, the safe zone of a maskable icon.
    """
    size = max(16, min(1024, int(size)))
    background = bytes((0x0B, 0x6E, 0x4F))
    white = bytes((255, 255, 255))
    left, right = round(size * 0.27), round(size * 0.73)
    bar = max(2, round(size * 0.13))
    top, bottom = round(size * 0.24), round(size * 0.76)
    cross_top, cross_bottom = round(size * 0.435), round(size * 0.565)
    plain = b"\x00" + background * size
    legs = (
        b"\x00"
        + background * left
        + white * bar
        + background * (right - left - 2 * bar)
        + white * bar
        + background * (size - right)
    )
    cross = b"\x00" + background * left + white * (right - left) + background * (size - right)
    rows = []
    for y in range(size):
        if cross_top <= y < cross_bottom:
            rows.append(cross)
        elif top <= y < bottom:
            rows.append(legs)
        else:
            rows.append(plain)
    header = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _chunk(b"IHDR", header)
        + _chunk(b"IDAT", zlib.compress(b"".join(rows), 9))
        + _chunk(b"IEND", b"")
    )


def inject(html: bytes) -> bytes:
    """Add the phone tags and the Cell script to one panel page."""
    lowered = html.lower()
    head = lowered.rfind(b"</head>")
    if head != -1:
        html = html[:head] + HEAD_SNIPPET.encode("utf-8") + html[head:]
        lowered = html.lower()
    tail = lowered.rfind(b"</body>")
    if tail != -1:
        html = html[:tail] + BODY_SNIPPET.encode("utf-8") + html[tail:]
    return html
