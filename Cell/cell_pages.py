_HUB_SCRIPT = r"""
(function () {
  var body = document.body;
  var mode = body.getAttribute("data-mode");
  var token = body.getAttribute("data-token") || "";
  function el(id) { return document.getElementById(id); }
  var since = 0;
  var leaving = false;
  var wantPanel = false;
  var tab = "out";
  var busy = false;
  var lastLog = 0;
  var failures = 0;
  var timer = null;
  var generation = 0;
  var shownLog = null;

  // One timer, and one answer in flight that counts. A page restored from the
  // browser's memory still has its old timer, and two chains of requests would
  // each add the same output lines.
  function schedule(delay) {
    if (timer !== null) window.clearTimeout(timer);
    timer = window.setTimeout(poll, delay);
  }
  function go(where) {
    if (leaving) return;
    leaving = true;
    window.location.replace(where);
    // A navigation that does not happen must not leave this page silent.
    window.setTimeout(function () { leaving = false; schedule(0); }, 8000);
  }
  function send(path, form) {
    return fetch(path, {
      method: "POST",
      headers: {"Content-Type": "application/x-www-form-urlencoded"},
      body: form || ""
    }).then(function (response) { return response.json(); });
  }
  function note(text) {
    var box = el("notice");
    box.textContent = text || "";
    box.hidden = !text;
  }
  function atBottom(node) {
    return node.scrollHeight - node.scrollTop - node.clientHeight < 40;
  }
  var kept = "";
  var partialLine = "";
  // True when something new arrived. The box is rewritten only then: rewriting it
  // on every answer drops a text selection, so nothing could be copied from it.
  function keepOutput(output) {
    var changed = Boolean(output.reset) || Boolean(output.lines && output.lines.length) ||
      (output.partial || "") !== partialLine;
    if (output.reset) kept = "";
    if (output.lines && output.lines.length) kept += output.lines.join("\n") + "\n";
    // Keep the page light on a long run: the newest part is what matters.
    if (kept.length > 200000) kept = kept.slice(kept.length - 150000);
    partialLine = output.partial || "";
    since = output.next;
    return changed;
  }
  function paintOutput() {
    if (tab !== "out") return;
    var out = el("out");
    var follow = atBottom(out);
    out.textContent = (kept + partialLine) || "No output yet.";
    if (follow) out.scrollTop = out.scrollHeight;
  }
  function showButtons(status) {
    var program = status.program;
    var panel = status.panel;
    var active = program.state === "starting" || program.state === "running" ||
      program.state === "stopping" || panel.open;
    el("start").hidden = active;
    el("open").hidden = !panel.open || mode === "working";
    el("stop").hidden = !active;
    el("stop").disabled = busy || program.state === "stopping";
    el("start").disabled = busy;
    el("sayBox").hidden = !(program.managed && program.state === "running");
  }
  function describe(status) {
    var program = status.program;
    var panel = status.panel;
    var title = "Program is not running";
    var detail = "Start it to open the option panel.";
    if (program.state === "starting") {
      title = "Starting the program";
      detail = "The option panel opens in a moment.";
    } else if (program.state === "stopping") {
      title = "Stopping the program";
      detail = "";
    } else if (panel.open) {
      title = mode === "working" ? "Working" : "Program is running";
      detail = panel.busy || panel.step === null ? "The panel is not answering at the moment."
        : "The panel is on step " + panel.step + ".";
      if (!program.managed) detail += " It was started on the computer.";
    } else if (program.state === "running") {
      title = "Program is running";
      detail = "It has no panel open right now.";
    } else if (program.state === "exited") {
      title = "Program finished";
      detail = "Exit code " + program.code + ".";
    }
    el("state").textContent = title;
    el("detail").textContent = detail;
    var progress = panel.progress;
    var work = el("work");
    if (progress && progress.active && progress.total) {
      work.hidden = false;
      el("bar").max = progress.total;
      el("bar").value = progress.done;
      var text = (progress.action || "Working") + " " + progress.done + " of " + progress.total;
      if (progress.label) text += ": " + progress.label;
      el("workLabel").textContent = text;
    } else if (mode === "working") {
      work.hidden = false;
      el("bar").removeAttribute("value");
      el("workLabel").textContent = "The program is working on the page you sent.";
    } else {
      work.hidden = true;
    }
    if (status.device) el("device").textContent = "Connected as " + status.device;
  }
  function render(status) {
    failures = 0;
    el("offline").hidden = true;
    describe(status);
    showButtons(status);
    if (status.output && keepOutput(status.output)) paintOutput();
    if (status.follow && status.follow.state !== "pending") {
      go(status.follow.go || "/");
      return;
    }
    if (mode !== "working" && wantPanel && status.panel.open) go("/");
  }
  function showLog() {
    fetch("/cell/log", {cache: "no-store"}).then(function (response) {
      return response.json();
    }).then(function (data) {
      if (tab !== "log") return;
      var text = data.lines.length ? data.lines.join("\n") : (data.note || "The run log is empty.");
      if (text === shownLog) return;
      shownLog = text;
      var view = el("out");
      var follow = atBottom(view);
      view.textContent = text;
      if (follow) view.scrollTop = view.scrollHeight;
    }).catch(function () {});
  }
  function poll() {
    timer = null;
    if (leaving) return;
    var mine = ++generation;
    var url = "/cell/status?since=" + since;
    if (token) url += "&t=" + encodeURIComponent(token);
    fetch(url, {cache: "no-store"}).then(function (response) {
      return response.json();
    }).then(function (status) {
      if (mine === generation) render(status);
    }).catch(function () {
      if (mine !== generation) return;
      failures += 1;
      if (failures >= 2) el("offline").hidden = false;
    }).then(function () {
      if (mine !== generation || leaving) return;
      if (tab === "log" && Date.now() - lastLog > 3000) { lastLog = Date.now(); showLog(); }
      schedule(document.visibilityState === "visible" ? 1200 : 5000);
    });
  }
  el("start").addEventListener("click", function () {
    busy = true; wantPanel = true; note("");
    el("start").disabled = true;
    send("/cell/start").then(function (answer) {
      busy = false;
      if (!answer.ok) { wantPanel = false; note(answer.message); }
    }).catch(function () { busy = false; note("The request did not reach the computer."); });
  });
  el("stop").addEventListener("click", function () {
    if (!window.confirm("Stop the program? A run in progress is interrupted.")) return;
    busy = true; wantPanel = false; note("");
    send("/cell/stop").then(function (answer) {
      busy = false;
      note(answer.message);
    }).catch(function () { busy = false; note("The request did not reach the computer."); });
  });
  el("say").addEventListener("submit", function (event) {
    event.preventDefault();
    var box = el("line");
    send("/cell/stdin", "line=" + encodeURIComponent(box.value)).then(function (answer) {
      if (answer.ok) box.value = "";
      else note(answer.message);
    }).catch(function () { note("The request did not reach the computer."); });
  });
  function pick(name) {
    tab = name;
    el("tabOut").setAttribute("aria-pressed", String(name === "out"));
    el("tabLog").setAttribute("aria-pressed", String(name === "log"));
    if (name === "log") {
      shownLog = null;
      el("out").textContent = "Reading the run log...";
      lastLog = Date.now();
      showLog();
    } else {
      paintOutput();
    }
  }
  el("tabOut").addEventListener("click", function () { pick("out"); });
  el("tabLog").addEventListener("click", function () { pick("log"); });
  document.addEventListener("visibilitychange", function () {
    // Ask at once when the phone wakes, instead of waiting out the slow timer.
    if (document.visibilityState === "visible" && !leaving) { failures = 0; schedule(0); }
  });
  window.addEventListener("pagehide", function () { leaving = true; });
  window.addEventListener("pageshow", function (event) {
    if (event.persisted) { leaving = false; schedule(0); }
  });
  var apple = /iPhone|iPad|iPod/.test(navigator.userAgent) ||
    (navigator.platform === "MacIntel" && navigator.maxTouchPoints > 1);
  var standalone = window.navigator.standalone === true ||
    (window.matchMedia && window.matchMedia("(display-mode: standalone)").matches);
  if (standalone) el("tips").hidden = true;
  else if (apple) el("tipAndroid").hidden = true;
  else el("tipApple").hidden = true;
  schedule(0);
})();
"""

