def _attribute(value: str) -> str:
    return value.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;").replace(">", "&gt;")


def hub_page(mode: str = "hub", token: str = "") -> bytes:
    """The Cell page. ``mode`` is ``hub``, or ``working`` while a sent page is processed."""
    own = "/cell/working?t=" + token if mode == "working" and token else "/cell/"
    html = (
        _HUB_HTML.replace("__HEAD__", _HEAD_FOR_HUB)
        .replace("__STYLE__", _HUB_STYLE)
        .replace("__MODE__", _attribute(mode))
        .replace("__TOKEN__", _attribute(token))
        .replace("__SELF__", _attribute(own))
        .replace("__SCRIPT__", _HUB_SCRIPT)
    )
    return html.encode("utf-8")


